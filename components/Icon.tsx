export type IconName = keyof typeof paths;

export function Icon({
  name,
  className = 'w-5 h-5',
  filled = false,
}: {
  name: IconName;
  className?: string;
  filled?: boolean;
}) {
  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      stroke={filled ? 'none' : 'currentColor'}
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {paths[name]
        .trim()
        .split(' M')
        .map((d, i) => (
          <path key={i} d={i === 0 ? d : `M${d}`} />
        ))}
    </svg>
  );
}

export function fileIconName(kind: string): IconName {
  switch (kind) {
    case 'markdown':
      return 'markdown';
    case 'image':
      return 'image';
    case 'video':
      return 'video';
    case 'code':
      return 'code';
    default:
      return 'file';
  }
}
